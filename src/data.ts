export interface Answer<T> {
  text: string | ((gender: Gender) => string);
  trait?: T;
  genderValue?: Gender;
}

export interface Question<T> {
  id: number;
  text: string | ((gender: Gender) => string);
  answers: Answer<T>[];
  isGenderQuestion?: boolean;
}

export const getText = (text: string | ((gender: Gender) => string), gender: Gender): string => {
  if (typeof text === 'function') {
    return text(gender);
  }
  return text;
};

